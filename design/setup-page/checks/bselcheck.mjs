import { chromium } from "@playwright/test";
const dir = new URL("../", import.meta.url).pathname;
const b = await chromium.launch(); const errs = [];
const p = await (await b.newContext({ viewport: { width: 1600, height: 1000 } })).newPage();
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(`file://${dir}out/setup-shell.html?calm=1`); await p.waitForTimeout(800);
await p.click("[data-act=wtab][data-id=backups]"); await p.waitForTimeout(100);
const width = await p.evaluate(() => [Math.round(document.querySelector(".mlw-blist").getBoundingClientRect().width), Math.round(document.querySelector(".mlw-backups").getBoundingClientRect().width)]);
const noFoundryBtn = await p.evaluate(() => ![...document.querySelectorAll(".mlw-bhead button")].some((x) => x.textContent.includes("Foundry")));
await p.screenshot({ path: `${dir}out/shots/b-4-wide.png`, clip: { x: 330, y: 200, width: 1210, height: 400 } });
await p.click("[data-act=bselect]"); await p.click('[data-act=bpick][data-id=v14]'); await p.waitForTimeout(80);
const head = await p.evaluate(() => document.querySelector(".mlw-bhead").innerText.replace(/\s+/g, " "));
await p.screenshot({ path: `${dir}out/shots/b-5-select.png`, clip: { x: 330, y: 200, width: 1210, height: 400 } });
await p.click("[data-act=bpickall]"); await p.waitForTimeout(60);
const all = await p.evaluate(() => document.querySelector(".mlw-bhead b").textContent);
await p.click("[data-act=bdelete]"); await p.waitForTimeout(100);
const left = await p.evaluate(() => [...document.querySelectorAll(".mlw-blist li .nm strong")].map((x) => x.textContent));
console.log({ width, noFoundryBtn, head, all, left }); console.log(errs.length ? errs : "no errors"); await b.close();
