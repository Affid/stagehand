import { chromium } from "@playwright/test";
const dir = new URL("../", import.meta.url).pathname;
const b = await chromium.launch(); const errs = [];
const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(`file://${dir}out/setup-shell.html?calm=1`); await p.evaluate(() => document.fonts.ready); await p.waitForTimeout(800);
await p.click('.mls-world[data-id="vaults"]'); await p.waitForTimeout(150);
await p.screenshot({ path: `${dir}out/shots/e-1-no-companion.png` });
console.log(await p.evaluate(() => document.querySelectorAll(".mls-main li.package, .mls-main .mlw-card").length), "cards");
console.log(errs.length ? errs : "no errors");
await b.close();
